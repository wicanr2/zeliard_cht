#!/usr/bin/env python3
"""Docker內把已審查居民註冊轉為固定Go資產表；不輸出原版或完整圖面。"""
import argparse
import hashlib
import json
from pathlib import Path

from PIL import Image


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--study", type=Path, required=True)
    ap.add_argument("--output", type=Path)
    ap.add_argument("--receipt", type=Path, required=True)
    args = ap.parse_args()
    sha = lambda b: hashlib.sha256(b).hexdigest()
    study = args.study
    registration = study/"town-npc-registration-v1/manifest.json"
    manifest = json.loads(registration.read_text(encoding="utf-8"))
    assert manifest["schema"] == 1 and len(manifest["frames"]) == 40
    assets = {a["group"]: a for a in manifest["artworks"]}
    assert set(assets) == set(range(5))
    raw_keys, rows = set(), []
    for frame in sorted(manifest["frames"], key=lambda f: (f["group"], f["phase"])):
        g, phase = frame["group"], frame["phase"]
        assert 0 <= g < 5 and 0 <= phase < 8 and (g, phase) not in raw_keys
        raw_keys.add((g, phase))
        asset = assets[g]
        path = study/"town-npc-art"/asset["file"]
        assert path.name == asset["file"] and sha(path.read_bytes()) == asset["sha256"]
        art = Image.open(path)
        assert art.size == (1448, 1086) and art.mode == "RGBA"
        native = Image.open(study/"town-npc-source-v2"/f"g{g}-p{phase}.png")
        assert native.mode == "RGBA" and native.size == (16, 24)
        assert sha((study/"town-npc-source-v2"/f"g{g}-p{phase}.png").read_bytes()) == frame["source_rgba_sha256"]
        assert native.getbbox() == tuple(frame["target_native"])
        x0, y0, x1, y1 = frame["crop"]
        assert 0 <= x0 < x1 <= art.width and 0 <= y0 < y1 <= art.height
        source_hash = sha(native.tobytes())
        crop, target = frame["crop"], frame["target_native"]
        rows.append(f'\t{{{g}, {phase}, "{asset["file"]}", "{asset["sha256"]}", "{source_hash}", image.Rect({", ".join(map(str,crop))}), image.Rect({", ".join(map(str,target))})}},')
    report = {"schema": 1, "status": "PASS_SOURCE_AND_ART_REGISTRATION", "frames": len(raw_keys), "groups": len(assets),
              "registration_sha256": sha(registration.read_bytes()), "source_contract": "docs/spec/035-town-residents-hd.md",
              "limits": "資產審查，不代表實際視窗或全遊戲HD完成"}
    if args.output:
        code = '// Code generated by tools/hd_compile_npcs.py; DO NOT EDIT.\n// 原版與手繪圖面只留本機；固定身份與裁切契約見規格035。\npackage hd\n\nimport "image"\n\nvar townNPCAssets = []townNPCAsset{\n'+"\n".join(rows)+'\n}\n'
        args.output.write_text(code, encoding="utf-8")
        report["generated_source_sha256"] = sha(code.encode())
    args.receipt.write_text(json.dumps(report, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False))


if __name__ == "__main__":
    main()
