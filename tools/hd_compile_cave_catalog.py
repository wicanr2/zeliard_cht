#!/usr/bin/env python3
"""Docker內編譯洞窟來源身份；Go產物只含數量／名稱／SHA，像素留本機。"""
import argparse
import hashlib
import json
from pathlib import Path

from hd_planar import convert


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--project", type=Path, required=True)
    ap.add_argument("--go-output", type=Path, required=True)
    ap.add_argument("--fixtures", type=Path, required=True)
    args = ap.parse_args()
    p = args.project
    out = args.fixtures
    assert out.is_dir() and not any(out.iterdir()), "fixture輸出須為既有空目錄"
    sha = lambda b: hashlib.sha256(b).hexdigest()
    base = p/"workplace/full-hd-v1"
    sources = json.loads((base/"cave-terrain-sources-v1/receipt.json").read_text())
    maps = json.loads((base/"cave-map-sources-v1/receipt.json").read_text())
    proof = json.loads((base/"cave-map-oracle-v1/receipt.json").read_text())
    assert len(proof["records"]) == 31 and all(x["matched"] for x in proof["records"])
    code = ["// Code generated by tools/hd_compile_cave_catalog.py; DO NOT EDIT.",
            "// 來源與限制見docs/spec/037-all-cave-terrain-hd.md；不包含原版像素。", "package hd", "",
            "var caveTerrainEntries = [...]caveTerrainEntry{"]
    for row in sources["profiles"]:
        raw = (p/row["source"]).read_bytes()
        assert sha(raw) == row["source_sha256"]
        header, pixels = raw[:48], convert(raw[48:])
        assert sha(header) == row["header_sha256"] and sha(pixels) == row["packed_sha256"]
        assert len(pixels) == row["tiles"]*48
        code.append(f'\t{{"{row["key"]}", {row["tiles"]}, "{sha(header)}", "{sha(pixels)}"}},')
        (out/(row["key"]+".resource")).write_bytes(header+pixels)
    code += ["}", "", "var caveMapEntries = [...]caveMapEntry{"]
    fixture_rows, seen = [], set()
    for row in maps["records"]:
        raw = (base/"cave-map-sources-v1"/row["source"]).read_bytes()
        assert sha(raw) == row["payload_sha256"]
        prefix = sha(raw[:19])
        assert prefix not in seen
        seen.add(prefix)
        key = row["name"].removesuffix(".MDT")
        code.append(f'\t{{{row["record"]}, "{key}", "{prefix}", {row["selector_raw"]}}},')
        (out/(key+".header")).write_bytes(raw[:19])
        fixture_rows.append({"record": row["record"], "name": key, "terrain": row["family_candidate"],
                             "header_file": key+".header", "header_sha256": prefix,
                             "resource_file": row["family_candidate"]+".resource"})
    code += ["}", ""]
    args.go_output.write_text("\n".join(code), encoding="utf-8")
    report = {"schema": 1, "status": "COMPILED_CAVE_SOURCE_IDENTITIES", "records": fixture_rows,
              "go_sha256_before_gofmt": sha(args.go_output.read_bytes()), "script_sha256": sha(Path(__file__).read_bytes()),
              "limits": "真實來源的結構fixture，未執行VM，不是正常到達其他地圖或HD驗收"}
    (out/"manifest.json").write_text(json.dumps(report, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print("COMPILED_CAVE_SOURCE_IDENTITIES", len(seen), len(sources["profiles"]))


if __name__ == "__main__":
    main()
